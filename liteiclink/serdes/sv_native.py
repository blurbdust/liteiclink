# Quartus Discovery --------------------------------------------------------------------------------

def _find_quartus_tool(name, quartus_bindir=None):
    """Locate a Quartus or Qsys binary. ip-generate lives in <quartus>/sopc_builder/bin, which a
    normal Quartus setup does not put on PATH."""
    if quartus_bindir is not None:
        for cand in [
            os.path.join(quartus_bindir, name),
            os.path.join(quartus_bindir, "..", "sopc_builder", "bin", name),
        ]:
            cand = os.path.normpath(cand)
            if os.path.exists(cand):
                return cand
    found = shutil.which(name)
    if found is not None:
        return found
    anchor = shutil.which("quartus_sh") or shutil.which("quartus_map")
    if anchor is not None:
        qbin = os.path.dirname(os.path.realpath(anchor))
        cand = os.path.normpath(os.path.join(qbin, "..", "sopc_builder", "bin", name))
        if os.path.exists(cand):
            return cand
    raise OSError(f"Could not find {name}. Put <quartus>/quartus/bin on PATH or pass quartus_bindir=.")

# IP Generation ------------------------------------------------------------------------------------

def generate_ip(component, name, device, params, output_dir, quartus_bindir=None, force=False):
    """Generate one Quartus IP with ip-generate and return (qip, top_verilog). Cached on a hash of
    every input that changes the output."""
    key    = "1" + component + device + repr(sorted(params.items()))
    digest = hashlib.sha256(key.encode()).hexdigest()[:16]

    output_dir = os.path.abspath(os.path.join(output_dir, name))
    os.makedirs(output_dir, exist_ok=True)
    stamp = os.path.join(output_dir, f"{name}.litex_hash")
    qip   = os.path.join(output_dir, f"{name}.qip")
    top   = os.path.join(output_dir, f"{name}.v")
    log   = os.path.join(output_dir, f"{name}.ip-generate.log")

    if not force and all(os.path.exists(p) for p in [qip, top, stamp]):
        with open(stamp) as f:
            if f.read().strip() == digest:
                print(f"[SVNative] Reusing cached {component} {name} (hash {digest}).")
                return qip, top

    cmd = [
        _find_quartus_tool("ip-generate", quartus_bindir),
        f"--component-name={component}",
        "--file-set=QUARTUS_SYNTH",
        f"--output-directory={output_dir}",
        f"--output-name={name}",
        "--system-info=DEVICE_FAMILY=Stratix V",
        f"--system-info=DEVICE={device}",
        # Without this, ip-generate writes no .qip for these components.
        f"--report-file=qip:{name}.qip",
        "--remove-qsys-generate-warning",
    ] + [f"--component-param={k}={v}" for k, v in sorted(params.items())]

    print(f"[SVNative] Generating {component} {name} for {device}.")
    r = subprocess.run(cmd, cwd=output_dir, capture_output=True, text=True)
    out = (r.stdout or "") + (r.stderr or "")
    with open(log, "w") as f:
        f.write(" ".join(cmd) + "\n\n" + out)
    # ip-generate can print errors for an illegal parameter combination and still exit 0.
    errors = [l for l in out.splitlines() if re.search(r"(^|\s)Error[: ]", l)]
    if r.returncode != 0 or errors or not (os.path.exists(qip) and os.path.exists(top)):
        raise OSError(f"[SVNative] ip-generate failed for {name}, see {log}:\n" + "\n".join(errors[:20]))

    with open(stamp, "w") as f:
        f.write(digest)
    return qip, top

def probe_ports(top_verilog):
    """Return {port: width} from a generated top level, so widths are read rather than assumed."""
    with open(top_verilog) as f:
        src = f.read()
    ports = {}
    for m in re.finditer(r"^\s*(?:input|output|inout)\s+wire\s*(?:\[\s*(\d+)\s*:\s*(\d+)\s*\])?\s*(\w+)",
        src, re.MULTILINE):
        hi, lo, name = m.groups()
        ports[name] = 1 if hi is None else int(hi) - int(lo) + 1
    return ports

# PRBS ---------------------------------------------------------------------------------------------

PRBS_OFF, PRBS7, PRBS15, PRBS31 = range(4)

class _PRBSGenerator(LiteXModule):
    """The sequence of litex.soc.cores.prbs.PRBSGenerator, `n_out` bits per cycle, with each bit
    written as the XOR of the state bits it depends on. Written as LiteX's recursion, every bit is
    an inline expression of the ones before it, and the Verilog grows exponentially with `n_out`."""
    def __init__(self, n_out, n_state, taps):
        self.o = Signal(n_out)

        # # #

        state = Signal(n_state, reset=1)

        # Bit masks over `state`, run through the same recursion.
        curval  = [1 << i for i in range(n_state)]
        curval += [0]*(n_out - n_state)
        for i in range(n_out):
            nv = 0
            for tap in taps:
                nv ^= curval[tap]
            curval.insert(0, nv)
            curval.pop()

        def xor(mask):
            return Reduce("XOR", [state[j] for j in range(n_state) if (mask >> j) & 1])

        self.sync += [
            state.eq(Cat(*[xor(m) for m in curval[:n_state]])),
            self.o.eq(Cat(*[xor(m) for m in curval])),
        ]

_PRBS_TAPS = {PRBS7: (7, [5, 6]), PRBS15: (15, [13, 14]), PRBS31: (31, [27, 30])}

class SVNativePRBSTX(LiteXModule):
    """PRBS generator for one channel, in the domain it is renamed to.

    `config`: 0 passes `i` through, 1/2/3 send PRBS7/15/31. The generators emit the oldest bit in
    the MSB and the serialiser sends bit 0 first, so `reverse` (the default for this PHY) puts the
    sequence on the wire in order. `invert` complements the word (polarity), `inject` flips bit 0 of
    one word. All inputs are in this domain.
    """
    def __init__(self, width):
        self.config  = Signal(2)
        self.reverse = Signal(reset=1)
        self.invert  = Signal()
        self.inject  = Signal()
        self.i       = Signal(width)
        self.o       = Signal(width)

        # # #

        assert width >= 31
        gens = {k: _PRBSGenerator(width, n, taps) for k, (n, taps) in _PRBS_TAPS.items()}
        self.submodules += gens.values()

        prbs  = Signal(width)
        cases = {PRBS_OFF: prbs.eq(self.i)}
        cases.update({k: prbs.eq(Mux(self.reverse, g.o[::-1], g.o)) for k, g in gens.items()})
        self.comb += Case(self.config, cases)

        self.sync += self.o.eq(prbs ^ Replicate(self.invert, width) ^ self.inject)

class SVNativePRBSRX(LiteXModule):
    """PRBS checker and counters for one channel, in the domain it is renamed to.

    The checker predicts each bit from the bits received before it, so it locks at any word
    alignment. Counters: `words` checked, `error_words` with at least one wrong bit, `error_bits`.
    `locked` is high after `lock_words` error-free words in a row and drops on any error. An input
    stuck for 1024 words counts as all bits wrong. `clear` zeroes the counters. Inputs are in this
    domain; `config` 0 stops checking.
    """
    def __init__(self, width, counter_width=48, lock_words=1024):
        self.config      = Signal(2)
        self.reverse     = Signal(reset=1)
        self.invert      = Signal()
        self.clear       = Signal()
        self.i           = Signal(width)
        self.o           = Signal(width)
        self.words       = Signal(counter_width)
        self.error_words = Signal(counter_width)
        self.error_bits  = Signal(counter_width)
        self.locked      = Signal()

        # # #

        # Input register, polarity and bit order.
        data = Signal(width)
        self.sync += [
            self.o.eq(self.i ^ Replicate(self.invert, width)),
            data.eq(Mux(self.reverse, self.o[::-1], self.o)),
        ]

        # Checkers (registered errors).
        chks = {PRBS7: PRBS7Checker(width), PRBS15: PRBS15Checker(width), PRBS31: PRBS31Checker(width)}
        self.submodules += chks.values()
        self.comb += [c.i.eq(data) for c in chks.values()]

        errors = Signal(width)
        active = Signal(4)
        cases  = {PRBS_OFF: errors.eq(0)}
        cases.update({k: errors.eq(c.errors) for k, c in chks.items()})
        self.sync += [
            Case(self.config, cases),
            active.eq(Cat(self.config != PRBS_OFF, active[:-1])),
        ]

        # Bit error count: popcount in groups of 8, then a sum, one register each.
        ngroups = (width + 7)//8
        groups  = [Signal(4) for _ in range(ngroups)]
        for n in range(ngroups):
            bits = [errors[b] for b in range(8*n, min(8*(n + 1), width))]
            self.sync += groups[n].eq(Reduce("ADD", bits))
        any_d   = Signal(2)
        nbits   = Signal(bits_for(width))
        self.sync += [
            any_d.eq(Cat(errors != 0, any_d[0])),
            nbits.eq(Reduce("ADD", groups)),
        ]

        # Counters. `errors` lands one cycle after `active[0]`, the sum two after.
        good = Signal(max=lock_words + 1)
        self.sync += [
            If(self.clear,
                self.words.eq(0),
                self.error_words.eq(0),
                self.error_bits.eq(0),
            ).Elif(active[3],
                self.words.eq(self.words + 1),
                self.error_words.eq(self.error_words + any_d[1]),
                self.error_bits.eq(self.error_bits + nbits),
            ),
            If(~active[3] | any_d[1],
                good.eq(0),
            ).Elif(good != lock_words,
                good.eq(good + 1),
            ),
        ]
        self.comb += self.locked.eq(good == lock_words)

# Clock Meter --------------------------------------------------------------------------------------

class _ClockMeter(LiteXModule):
    """Frequency of clock domain `cd` in Hz, counted over `gate_cycles` of sys. A free-running Gray
    counter in `cd` ignores that domain's reset, so a clock held in reset still measures."""
    def __init__(self, cd, gate_cycles, width=8):
        self.value = Signal(32)

        # # #

        count = Signal(width, reset_less=True)
        gray  = Signal(width, reset_less=True)
        sync  = getattr(self.sync, cd)
        sync += [
            count.eq(count + 1),
            gray.eq(count ^ (count >> 1)),
        ]

        gray_s = Signal(width)
        self.specials += MultiReg(gray, gray_s, "sys")
        bits = [gray_s[width - 1]]
        for b in reversed(range(width - 1)):
            bits.insert(0, bits[0] ^ gray_s[b])
        binary = Signal(width)
        self.comb += binary.eq(Cat(*bits))

        last  = Signal(width)
        delta = Signal(width)
        acc   = Signal(32)
        gate  = Signal(max=gate_cycles + 1)
        self.comb += delta.eq(binary - last)
        self.sync += [
            last.eq(binary),
            If(gate == gate_cycles - 1,
                gate.eq(0),
                self.value.eq(acc + delta),
                acc.eq(0),
            ).Else(
                gate.eq(gate + 1),
                acc.eq(acc + delta),
            ),
        ]

# Stratix V Native PHY, PMA Direct ------------------------------------------------------------------

class SVNative(LiteXModule):
    """Stratix V transceiver channels in PMA direct mode.

    `pads` has `tx_p` and `rx_p` with one bit per channel (Quartus places the negatives). `refclk`
    is the transceiver reference clock pin, driving both the transmit PLLs and the receive CDRs.

    Per channel i, the fabric sees clock domains `<cd_prefix>_tx<i>` and `<cd_prefix>_rx<i>`, at
    `data_rate`/`data_width`, and the words `tx_data[i]` (sent when the channel's PRBS is off) and
    `rx_data[i]`. The sys domain is the management clock of the reconfiguration controller and the
    reset sequencer, which Intel specifies at 100 to 125 MHz.

    `pll_type` picks the transmit PLLs. A CMU PLL is a channel's own PLL, so that channel loses its
    receiver: a bank whose six channels all carry data needs `"ATX"`.
    """
    def __init__(self, platform, pads, refclk, refclk_freq, data_rate, sys_clk_freq,
        data_width     = 80,
        name           = "sv_native",
        cd_prefix      = None,
        output_dir     = "sv_native_ip",
        pll_type       = "CMU",
        with_analog    = True,
        quartus_bindir = None):
        assert data_width in [8, 10, 16, 20, 32, 40, 64, 80]
        assert pll_type in ["CMU", "ATX"]
        assert 100e6 <= sys_clk_freq <= 125e6, "the reconfiguration controller needs 100-125 MHz"
        n = len(pads.tx_p)
        assert len(pads.rx_p) == n
        cd_prefix = name if cd_prefix is None else cd_prefix

        self.nchannels  = n
        self.data_width = data_width
        self.data_rate  = data_rate
        self.cd_names   = [(f"{cd_prefix}_tx{i}", f"{cd_prefix}_rx{i}") for i in range(n)]

        # Fabric data.
        self.tx_data = [Signal(data_width) for _ in range(n)]
        self.rx_data = [Signal(data_width) for _ in range(n)]

        # Control (sys domain).
        self.reset       = Signal()
        self.loopback    = Signal(n)
        self.lock_to_ref = Signal(n)
        self.tx_invert   = Signal(n)
        self.rx_invert   = Signal(n)
        self.reverse     = Signal(reset=1)
        self.tx_prbs     = [Signal(2) for _ in range(n)]
        self.rx_prbs     = [Signal(2) for _ in range(n)]
        self.inject      = Signal(n)  # Pulse.
        self.clear       = Signal(n)  # Pulse.

        # Status (sys domain).
        self.pll_locked       = Signal(n)
        self.tx_ready         = Signal(n)
        self.rx_ready         = Signal(n)
        self.rx_locked_data   = Signal(n)
        self.rx_locked_ref    = Signal(n)
        self.tx_cal_busy      = Signal(n)
        self.rx_cal_busy      = Signal(n)
        self.reconfig_busy    = Signal()
        self.prbs_locked      = Signal(n)
        self.tx_freq          = [Signal(32) for _ in range(n)]
        self.rx_freq          = [Signal(32) for _ in range(n)]
        self.prbs_words       = [Signal(48) for _ in range(n)]
        self.prbs_error_words = [Signal(48) for _ in range(n)]
        self.prbs_error_bits  = [Signal(48) for _ in range(n)]

        # Reconfiguration controller management port (sys domain, Avalon-MM, word addresses).
        self.mgmt_address     = Signal(7)
        self.mgmt_read        = Signal()
        self.mgmt_write       = Signal()
        self.mgmt_writedata   = Signal(32)
        self.mgmt_readdata    = Signal(32)
        self.mgmt_waitrequest = Signal()

        # # #

        device = platform.device

        # Native PHY -------------------------------------------------------------------------------
        mhz = lambda f: f"{f/1e6:.10g} MHz"
        phy_params = {
            "channels"                          : n,
            "pma_direct_width"                  : data_width,
            "set_data_rate"                     : f"{data_rate/1e6:.10g}",
            "set_cdr_refclk_freq"               : mhz(refclk_freq),
            "gui_pll_reconfig_pll0_refclk_freq" : mhz(refclk_freq),
            "gui_pll_reconfig_pll0_pll_type"    : pll_type,
            "enable_port_rx_seriallpbken"       : 1,
            "enable_port_rx_pma_clkout"         : 1,
        }
        phy_qip, phy_top = generate_ip("altera_xcvr_native_sv", f"{name}_phy", device, phy_params,
            output_dir, quartus_bindir)
        platform.add_ip(phy_qip)
        ports = probe_ports(phy_top)
        for p, w in {"tx_pma_parallel_data": n*data_width, "rx_pma_parallel_data": n*data_width,
            "tx_pma_clkout": n, "rx_pma_clkout": n, "pll_locked": n, "rx_seriallpbken": n}.items():
            if ports.get(p) != w:
                raise ValueError(f"[SVNative] {phy_top}: expected {p}[{w}], found {ports.get(p)}.")
        # One reconfiguration interface per channel and per transmit PLL, 70 bits each way in.
        ninterfaces = ports["reconfig_to_xcvr"]//70
        assert ninterfaces*70 == ports["reconfig_to_xcvr"]

        # Reconfiguration Controller ---------------------------------------------------------------
        rcfg_params = {
            "number_of_reconfig_interfaces" : ninterfaces,
            "enable_offset"                 : 1,
            "enable_analog"                 : int(with_analog),
            "enable_dcd"                    : 0,
            "enable_dcd_power_up"           : 1,
            "enable_eyemon"                 : 0,
            "ber_en"                        : 0,
            "enable_dfe"                    : 0,
            "enable_adce"                   : 0,
            "enable_mif"                    : 0,
            "gui_enable_pll"                : 0,
            "gui_cal_status_port"           : "false",
        }
        rcfg_qip, rcfg_top = generate_ip("alt_xcvr_reconfig", f"{name}_reconfig", device, rcfg_params,
            output_dir, quartus_bindir)
        platform.add_ip(rcfg_qip)
        rports = probe_ports(rcfg_top)
        if (rports.get("reconfig_to_xcvr"), rports.get("reconfig_from_xcvr")) != \
           (ports["reconfig_to_xcvr"], ports["reconfig_from_xcvr"]):
            raise ValueError(f"[SVNative] reconfiguration bus widths differ: {rcfg_top} vs {phy_top}.")

        # Reset Controller -------------------------------------------------------------------------
        # One logical PLL: its power-down drives every channel's PLL from one register, which is what
        # lets Quartus merge them, and its lock is the AND of theirs.
        rst_params = {
            "CHANNELS"          : n,
            "PLLS"              : 1,
            "SYS_CLK_IN_MHZ"    : int(sys_clk_freq/1e6),
            "SYNCHRONIZE_RESET" : 1,
            "TX_PLL_ENABLE"     : 1,
            "TX_ENABLE"         : 1,
            "TX_PER_CHANNEL"    : 0,
            "RX_ENABLE"         : 1,
            "RX_PER_CHANNEL"    : 1,
        }
        rst_qip, rst_top = generate_ip("altera_xcvr_reset_control", f"{name}_reset", device, rst_params,
            output_dir, quartus_bindir)
        platform.add_ip(rst_qip)

        # Clock Domains ----------------------------------------------------------------------------
        tx_clk = Signal(n)
        rx_clk = Signal(n)
        for i, (tx_cd, rx_cd) in enumerate(self.cd_names):
            for cd_name, clk, ready in [(tx_cd, tx_clk[i], self.tx_ready[i]), (rx_cd, rx_clk[i], self.rx_ready[i])]:
                cd = ClockDomain(cd_name)
                setattr(self, "cd_" + cd_name, cd)
                self.comb += cd.clk.eq(clk)
                self.specials += AsyncResetSynchronizer(cd, ~ready)

        # Instances --------------------------------------------------------------------------------
        to_xcvr   = Signal(ports["reconfig_to_xcvr"])
        from_xcvr = Signal(ports["reconfig_from_xcvr"])

        pll_powerdown   = Signal()
        tx_analogreset  = Signal(n)
        tx_digitalreset = Signal(n)
        rx_analogreset  = Signal(n)
        rx_digitalreset = Signal(n)

        tx_parallel = Signal(n*data_width)
        rx_parallel = Signal(n*data_width)

        self.specials += Instance(f"{name}_phy",
            i_pll_powerdown        = Replicate(pll_powerdown, n),
            i_tx_analogreset       = tx_analogreset,
            i_tx_digitalreset      = tx_digitalreset,
            i_rx_analogreset       = rx_analogreset,
            i_rx_digitalreset      = rx_digitalreset,
            i_tx_pll_refclk        = refclk,
            i_rx_cdr_refclk        = refclk,
            o_tx_pma_clkout        = tx_clk,
            o_rx_pma_clkout        = rx_clk,
            o_tx_serial_data       = pads.tx_p,
            i_rx_serial_data       = pads.rx_p,
            i_tx_pma_parallel_data = tx_parallel,
            o_rx_pma_parallel_data = rx_parallel,
            o_pll_locked           = self.pll_locked,
            i_rx_set_locktodata    = 0,
            i_rx_set_locktoref     = self.lock_to_ref,
            o_rx_is_lockedtoref    = self.rx_locked_ref,
            o_rx_is_lockedtodata   = self.rx_locked_data,
            i_rx_seriallpbken      = self.loopback,
            o_tx_cal_busy          = self.tx_cal_busy,
            o_rx_cal_busy          = self.rx_cal_busy,
            i_reconfig_to_xcvr     = to_xcvr,
            o_reconfig_from_xcvr   = from_xcvr,
        )

        self.specials += Instance(f"{name}_reconfig",
            i_mgmt_clk_clk              = ClockSignal("sys"),
            i_mgmt_rst_reset            = ResetSignal("sys"),
            o_reconfig_busy             = self.reconfig_busy,
            i_reconfig_mgmt_address     = self.mgmt_address,
            i_reconfig_mgmt_read        = self.mgmt_read,
            o_reconfig_mgmt_readdata    = self.mgmt_readdata,
            o_reconfig_mgmt_waitrequest = self.mgmt_waitrequest,
            i_reconfig_mgmt_write       = self.mgmt_write,
            i_reconfig_mgmt_writedata   = self.mgmt_writedata,
            o_reconfig_to_xcvr          = to_xcvr,
            i_reconfig_from_xcvr        = from_xcvr,
        )

        self.specials += Instance(f"{name}_reset",
            i_clock              = ClockSignal("sys"),
            i_reset              = ResetSignal("sys") | self.reset,
            o_pll_powerdown      = pll_powerdown,
            o_tx_analogreset     = tx_analogreset,
            o_tx_digitalreset    = tx_digitalreset,
            o_tx_ready           = self.tx_ready,
            i_pll_locked         = self.pll_locked == (2**n - 1),
            i_pll_select         = 0,
            i_tx_cal_busy        = self.tx_cal_busy,
            o_rx_analogreset     = rx_analogreset,
            o_rx_digitalreset    = rx_digitalreset,
            o_rx_ready           = self.rx_ready,
            i_rx_is_lockedtodata = self.rx_locked_data,
            i_rx_cal_busy        = self.rx_cal_busy,
        )

        # Per-Channel Datapath ---------------------------------------------------------------------
        gate = int(sys_clk_freq)
        for i, (tx_cd, rx_cd) in enumerate(self.cd_names):
            W = data_width

            # TX: PRBS or user data, polarity, error injection.
            prbs_tx = ClockDomainsRenamer(tx_cd)(SVNativePRBSTX(W))
            inject  = PulseSynchronizer("sys", tx_cd)
            self.submodules += prbs_tx, inject
            self.comb += [
                inject.i.eq(self.inject[i]),
                prbs_tx.inject.eq(inject.o),
                prbs_tx.i.eq(self.tx_data[i]),
                tx_parallel[W*i:W*(i + 1)].eq(prbs_tx.o),
            ]
            self.specials += [
                MultiReg(self.tx_prbs[i],   prbs_tx.config,  tx_cd),
                MultiReg(self.reverse,      prbs_tx.reverse, tx_cd, reset=1),
                MultiReg(self.tx_invert[i], prbs_tx.invert,  tx_cd),
            ]

            # RX: polarity, PRBS check and counters.
            prbs_rx = ClockDomainsRenamer(rx_cd)(SVNativePRBSRX(W))
            clear   = PulseSynchronizer("sys", rx_cd)
            self.submodules += prbs_rx, clear
            self.comb += [
                clear.i.eq(self.clear[i]),
                prbs_rx.clear.eq(clear.o),
                prbs_rx.i.eq(rx_parallel[W*i:W*(i + 1)]),
                self.rx_data[i].eq(prbs_rx.o),
            ]
            self.specials += [
                MultiReg(self.rx_prbs[i],   prbs_rx.config,  rx_cd),
                MultiReg(self.reverse,      prbs_rx.reverse, rx_cd, reset=1),
                MultiReg(self.rx_invert[i], prbs_rx.invert,  rx_cd),
                MultiReg(prbs_rx.locked,    self.prbs_locked[i], "sys"),
            ]
            for src, dst in [(prbs_rx.words, self.prbs_words[i]),
                             (prbs_rx.error_words, self.prbs_error_words[i]),
                             (prbs_rx.error_bits, self.prbs_error_bits[i])]:
                bs = BusSynchronizer(len(src), rx_cd, "sys")
                self.submodules += bs
                self.comb += [bs.i.eq(src), dst.eq(bs.o)]

            # Clock meters.
            for cd, freq in [(tx_cd, self.tx_freq[i]), (rx_cd, self.rx_freq[i])]:
                meter = _ClockMeter(cd, gate)
                self.submodules += meter
                self.comb += freq.eq(meter.value)

    def add_timing_constraints(self, platform, refclk, refclk_freq, sys_clk="{sys_clk}"):
        # derive_pll_clocks derives the transceiver clocks from the reference clock: the fabric sees
        # each channel's TX clock as `...|tx_pma_ch.pclk_from_cgb[n]` and its RX clock as
        # `...|rx_pma_deser|clk90b`. Every crossing between them and sys goes through a
        # synchroniser, so sys is made asynchronous to all of them. `sys_clk` is a get_clocks
        # pattern, braces included, and must match: TimeQuest only warns about an empty group.
        platform.add_period_constraint(refclk, 1e9/refclk_freq)
        platform.toolchain.additional_sdc_commands += [
            f"set_clock_groups -asynchronous -group [get_clocks {sys_clk}]",
        ]

    def add_controls(self):
        n = self.nchannels

        self._control = CSRStorage(description="PHY control.", fields=[
            CSRField("reset",   size=1, offset=0, description="Hold the PLLs and channels in reset (restarts the reset sequence)."),
            CSRField("reverse", size=1, offset=1, reset=1, description="PRBS bit order. 1: oldest bit in bit 0, which the serialiser sends first."),
        ])
        self._loopback    = CSRStorage(n,   description="Internal serial loopback, TX serialiser to RX CDR, per channel.")
        self._lock_to_ref = CSRStorage(n,   description="Force the RX CDR to lock to the reference clock, per channel.")
        self._tx_invert   = CSRStorage(n,   description="Invert TX data (polarity), per channel.")
        self._rx_invert   = CSRStorage(n,   description="Invert RX data (polarity), per channel.")
        self._tx_prbs     = CSRStorage(2*n, description="TX pattern, 2 bits per channel: 0 data, 1 PRBS7, 2 PRBS15, 3 PRBS31.")
        self._rx_prbs     = CSRStorage(2*n, description="RX checker, 2 bits per channel: 0 off, 1 PRBS7, 2 PRBS15, 3 PRBS31.")
        self._inject      = CSR(n)
        self._clear       = CSR(n)
        self._latch       = CSR()

        # Live status, one bit per channel in each. The transceiver's are asynchronous.
        status = {
            "pll_locked"     : self.pll_locked,
            "tx_ready"       : self.tx_ready,
            "rx_ready"       : self.rx_ready,
            "rx_locked_data" : self.rx_locked_data,
            "rx_locked_ref"  : self.rx_locked_ref,
            "prbs_locked"    : self.prbs_locked,
            "tx_cal_busy"    : self.tx_cal_busy,
            "rx_cal_busy"    : self.rx_cal_busy,
        }
        for name, sig in status.items():
            csr = CSRStatus(n, name=name)
            setattr(self, "_" + name, csr)
            self.specials += MultiReg(sig, csr.status)
        self._reconfig_busy = CSRStatus()
        self.specials += MultiReg(self.reconfig_busy, self._reconfig_busy.status)

        self.comb += [
            self.reset.eq(self._control.fields.reset),
            self.reverse.eq(self._control.fields.reverse),
            self.loopback.eq(self._loopback.storage),
            self.lock_to_ref.eq(self._lock_to_ref.storage),
            self.tx_invert.eq(self._tx_invert.storage),
            self.rx_invert.eq(self._rx_invert.storage),
            self.inject.eq(Mux(self._inject.re, self._inject.r, 0)),
            self.clear.eq(Mux(self._clear.re, self._clear.r, 0)),
        ]
        for i in range(n):
            self.comb += [
                self.tx_prbs[i].eq(self._tx_prbs.storage[2*i:2*(i + 1)]),
                self.rx_prbs[i].eq(self._rx_prbs.storage[2*i:2*(i + 1)]),
            ]

        # Counters and frequencies, latched together by a write to `latch` so that a 64-bit value
        # read as two words cannot tear.
        for i in range(n):
            for name, sig, width in [
                ("tx_freq",     self.tx_freq[i],          32),
                ("rx_freq",     self.rx_freq[i],          32),
                ("words",       self.prbs_words[i],       64),
                ("error_words", self.prbs_error_words[i], 64),
                ("error_bits",  self.prbs_error_bits[i],  64),
            ]:
                csr = CSRStatus(width, name=f"ch{i}_{name}")
                setattr(self, f"_ch{i}_{name}", csr)
                self.sync += If(self._latch.re, csr.status.eq(sig))

        # Reconfiguration controller management port: write the address and data, then `mgmt_cmd`
        # (1 read, 2 write), and poll `mgmt_status.done`.
        self._mgmt_address = CSRStorage(7)
        self._mgmt_wdata   = CSRStorage(32)
        self._mgmt_cmd     = CSR(2)
        self._mgmt_rdata   = CSRStatus(32)
        self._mgmt_status  = CSRStatus(fields=[
            CSRField("busy", size=1, offset=0),
            CSRField("done", size=1, offset=1),
        ])
        busy  = Signal()
        done  = Signal()
        write = Signal()
        self.comb += [
            self.mgmt_address.eq(self._mgmt_address.storage),
            self.mgmt_writedata.eq(self._mgmt_wdata.storage),
            self.mgmt_read.eq(busy & ~write),
            self.mgmt_write.eq(busy & write),
            self._mgmt_status.fields.busy.eq(busy),
            self._mgmt_status.fields.done.eq(done),
        ]
        self.sync += [
            If(~busy & self._mgmt_cmd.re & (self._mgmt_cmd.r != 0),
                busy.eq(1),
                done.eq(0),
                write.eq(self._mgmt_cmd.r[1]),
            ).Elif(busy & ~self.mgmt_waitrequest,
                busy.eq(0),
                done.eq(1),
                If(~write, self._mgmt_rdata.status.eq(self.mgmt_readdata)),
            ),
        ]
