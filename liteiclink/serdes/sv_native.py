"""
Altera/Intel Stratix V transceivers through the Native PHY in PMA direct mode.

The Native PHY (`altera_xcvr_native_sv`) is generated by Quartus at build time with no PCS: each
channel hands the fabric a raw parallel word, `data_width` bits per cycle, serialised bit 0 first,
on that channel's own clocks (`tx_pma_clkout` and the recovered `rx_pma_clkout`). Channels are not
bonded; Quartus merges their transmit PLLs where the clock network allows.

Two more generated IPs complete it, as on every Stratix V transceiver design:

- `alt_xcvr_reconfig`, the Transceiver Reconfiguration Controller. Mandatory: it runs the receiver
  offset cancellation at start-up. With `with_analog`, its management port (exposed as CSRs by
  `add_controls`) also reaches the PMA analog settings (VOD, pre-emphasis, equalisation).
- `altera_xcvr_reset_control`, Intel's reset sequencer for the PLL power-down and the TX/RX
  analog and digital resets.

All three are cached on a hash of their parameters, as `litepcie.phy.svpciephy` does.

Each channel carries a PRBS7/15/31 generator and checker. The checker is self-synchronising, so it
needs no word alignment, and counts checked words, words with errors and bit errors. Internal
serial loopback, forced lock-to-reference, polarity inversion and error injection are per channel.

Reference: Intel doc 683797 (formerly SV52004), Stratix V Transceiver PHY IP Core User Guide.
"""

